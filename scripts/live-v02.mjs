store.undo();assert.notEqual(store.project.layers.find(l=>l.id===target).gain,.12);store.redo();
const final=renderProject(store.project);assert.equal(final.clipped,0);
await writeFile(new URL('../outputs/v0.2/ai-after.soniloom.json',import.meta.url),serializeProject(store.project));
await writeFile(new URL('../outputs/v0.2/ai-after.wav',import.meta.url),new Uint8Array(encodeWav(final.channels)));
console.log('PASS: real creation + three scoped edits; stable IDs; protected PCM; undo/redo; unclipped final WAV');
