import {mkdir,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {createProject,ProjectStore,serializeProject} from '../src/project.mjs';
import {projectContext,prepareProposal,applyProposal} from '../src/ai-contract.mjs';
import {renderProject} from '../src/engine.mjs';
import {encodeWav} from '../src/wav.mjs';
const origin='http://127.0.0.1:8795';
const status=await (await fetch(origin+'/api/status')).json();
if(!status.configured)throw Error('Dedicated key unavailable');
const p=createProject();p.layers=[];p.name='AI acceptance';const store=new ProjectStore(p),history=[],evidence=[];
await mkdir(new URL('../outputs/v0.2/',import.meta.url),{recursive:true});
async function turn(prompt,scope='all'){
 const started=Date.now(),response=await fetch(origin+'/api/propose',{method:'POST',headers:{'Content-Type':'application/json',Origin:origin,'X-SoniLoom-Token':status.clientToken},body:JSON.stringify({prompt,scope,project:projectContext(store.project),history:history.slice(-10)})});
 const data=await response.json();if(!response.ok)throw Error(data.error);
 const proposal=prepareProposal(store,data.proposal,{scope});assert.ok(proposal.changes.length,'Expected actionable provider proposal');
 const before=store.project;applyProposal(store,proposal);const after=store.project;
 evidence.push({prompt,scope,model:data.model,responseId:data.responseId,usage:data.usage,budget:data.budget,elapsedMs:Date.now()-started,proposal:data.proposal,changes:proposal.changes,projectId:after.id,generation:store.generation});
 history.push({role:'user',content:prompt},{role:'assistant',content:data.proposal.message+' [Applied successfully]'});
 await writeFile(new URL('../outputs/v0.2/provider-evidence.json',import.meta.url),JSON.stringify(evidence,null,2));
 console.log(JSON.stringify({turn:evidence.length,operations:data.proposal.operations.length,changes:proposal.changes.length,estimatedUSD:data.budget.estimatedUSD,reservedUSD:data.budget.reservedUSD}));
 return {before,after};
}
await turn('创建一个6秒的科幻飞船启动音效，分成机械点火、能量上升、引擎释放三个独立声层。使用你可以组合的声源，整体留足音量余量。给每层清楚的名字。');
assert.equal(store.project.layers.length,3);const ids=store.project.layers.map(l=>l.id),protectedId=ids[0],target=ids[1];store.lock(protectedId,true);
const base=store.project,protectedPCM=renderProject(base).layers[protectedId];
await writeFile(new URL('../outputs/v0.2/ai-before.soniloom.json',import.meta.url),serializeProject(base));
await writeFile(new URL('../outputs/v0.2/ai-before.wav',import.meta.url),new Uint8Array(encodeWav(renderProject(base).channels)));
await turn('只把这个选中声层的低通截止频率改成1800 Hz，使它更暗，其余参数不变。',target);
