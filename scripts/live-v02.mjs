await turn('继续修改同一个选中声层，只把结束频率改成600 Hz，保留刚才的1800 Hz截止频率。',target);
assert.equal(store.project.layers.find(l=>l.id===target).endFrequency,600);
await turn('最后只把当前选中声层的音量改成0.12，其他所有层和参数都保持不变。',target);
